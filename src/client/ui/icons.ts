const cache = new Map<string, string>();
export function icon(id: string | undefined, className = "") {
  const name = mapping[id || ""] || id || "star";
  if (!cache.has(name)) {
    let path = "";
    for (const [y, row] of (pixels[name || ""] || pixels.star).entries())
      for (let x = 0; x < row.length; x++)
        if (row[x] === "#") path += `M${x + 2} ${y + 2}h1v1h-1z`;
    cache.set(name, path);
  }
  return `<svg class="sigil ${className}" viewBox="0 0 16 16" aria-hidden="true" fill="currentColor"><path d="${cache.get(name)}"/></svg>`;
}
